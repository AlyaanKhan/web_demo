// Generates the vector logo system from real font outlines.
//   node scripts/build-logo.mjs
// Outputs: src/components/brand/logoPaths.ts and public/brand/*.svg
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import * as opentypeNs from 'opentype.js'

const opentype = opentypeNs.default ?? opentypeNs
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const font = (p) => {
  const b = readFileSync(resolve(root, 'node_modules/@fontsource', p))
  return opentype.parse(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength))
}

const serif = font('cormorant-garamond/files/cormorant-garamond-latin-700-normal.woff')
const sansBold = font('plus-jakarta-sans/files/plus-jakarta-sans-latin-800-normal.woff')
const sansSemi = font('plus-jakarta-sans/files/plus-jakarta-sans-latin-700-normal.woff')

const r2 = (n) => Math.round(n * 100) / 100

// opentype's toPathData() can emit NaN when rounding, so serialise commands ourselves.
function toD(path) {
  return path.commands
    .map((c) => {
      if (c.type === 'Z') return 'Z'
      if (c.type === 'Q') return `Q${r2(c.x1)} ${r2(c.y1)} ${r2(c.x)} ${r2(c.y)}`
      if (c.type === 'C') return `C${r2(c.x1)} ${r2(c.y1)} ${r2(c.x2)} ${r2(c.y2)} ${r2(c.x)} ${r2(c.y)}`
      return `${c.type}${r2(c.x)} ${r2(c.y)}`
    })
    .join('')
}

// ---- Mark geometry: three overlapping circles, spacing 1.66r like the original ----
const R = 50
const SPACING = 83
const CY = 50
const circles = [0, 1, 2].map((i) => ({ cx: R + i * SPACING, cy: CY, r: R }))
const MARK_W = 2 * R + 2 * SPACING // 266
const MARK_H = 2 * R // 100

/** Glyph path for a single char, scaled to a target height and centred on (cx, cy). */
function glyph(ch, cx, cy, targetH, f = serif) {
  const probe = f.getPath(ch, 0, 0, 100)
  const bb = probe.getBoundingBox()
  const scale = targetH / (bb.y2 - bb.y1)
  const size = 100 * scale
  const p0 = f.getPath(ch, 0, 0, size).getBoundingBox()
  const x = cx - (p0.x1 + p0.x2) / 2
  const y = cy - (p0.y1 + p0.y2) / 2
  return toD(f.getPath(ch, x, y, size))
}

function letters(set) {
  const [a, b, c] = set
  return [
    glyph(a, circles[0].cx + 2, CY + 1, 88),
    glyph(b, circles[1].cx, CY + 1, 92),
    glyph(c, circles[2].cx + (c === 'E' ? 1 : 2), CY + 1, 84),
  ]
}

/** Lay out a string with tracking (em) and kerning; returns {d, width, ascent} with baseline at y. */
function text(str, f, size, x, y, tracking = 0) {
  const glyphs = [...str].map((c) => f.charToGlyph(c))
  const scale = size / f.unitsPerEm
  let pen = x
  const parts = []
  glyphs.forEach((g, i) => {
    parts.push(toD(g.getPath(pen, y, size)))
    pen += g.advanceWidth * scale + tracking * size
    if (i < glyphs.length - 1) pen += f.getKerningValue(g, glyphs[i + 1]) * scale
  })
  return { d: parts.join(''), width: pen - x - tracking * size }
}

const SFE = letters(['S', 'f', 'E'])
const SFS = letters(['S', 'f', 'S'])

// ---- TS module for the React <Logo/> (animated, themable) ----
mkdirSync(resolve(root, 'src/components/brand'), { recursive: true })
writeFileSync(
  resolve(root, 'src/components/brand/logoPaths.ts'),
  `// AUTO-GENERATED by scripts/build-logo.mjs. Do not edit by hand.
export const MARK_VIEWBOX = { w: ${MARK_W}, h: ${MARK_H} } as const
export const MARK_CIRCLES = ${JSON.stringify(circles)} as const
export const LETTERS = {
  SfE: ${JSON.stringify(SFE)},
  SfS: ${JSON.stringify(SFS)},
} as const
export type LetterSet = keyof typeof LETTERS
`,
)

// ---- Static SVG assets ----
const STOPS = `
    <stop offset="0" stop-color="#1E1B3F"/>
    <stop offset=".38" stop-color="#46426E"/>
    <stop offset=".64" stop-color="#3C6F70"/>
    <stop offset="1" stop-color="#A3C2B9"/>`

function markGroup(id, lettersD, ox = 0, oy = 0, s = 1) {
  const c = circles
    .map(
      (k, i) =>
        `<circle cx="${k.cx}" cy="${k.cy}" r="${k.r}" fill="url(#${id}-g)"${i ? ` filter="url(#${id}-s)"` : ''}/>`,
    )
    .join('')
  const l = lettersD.map((d) => `<path d="${d}"/>`).join('')
  return `<g transform="translate(${ox} ${oy}) scale(${s})">${c}<g fill="#fff">${l}</g></g>`
}
function defs(id, x0, w) {
  return `<defs>
  <linearGradient id="${id}-g" gradientUnits="userSpaceOnUse" x1="${x0}" y1="0" x2="${x0 + w}" y2="0">${STOPS}
  </linearGradient>
  <filter id="${id}-s" x="-20%" y="-20%" width="140%" height="140%">
    <feDropShadow dx="-2.5" dy="0" stdDeviation="2" flood-color="#0b0a1f" flood-opacity=".28"/>
  </filter>
</defs>`
}
const svg = (w, h, body, title) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${r2(w)} ${r2(h)}" role="img" aria-label="${title}"><title>${title}</title>${body}</svg>\n`

const out = (name, s) => writeFileSync(resolve(root, 'public/brand', name), s)
mkdirSync(resolve(root, 'public/brand'), { recursive: true })

// Mark only (pad 6 for the shadow)
out('sfe-mark.svg', svg(MARK_W + 12, MARK_H + 12, defs('m', 0, MARK_W) + markGroup('m', SFE, 6, 6), 'Strategies for Excellence'))
out('sfs-mark-original.svg', svg(MARK_W + 12, MARK_H + 12, defs('m', 0, MARK_W) + markGroup('m', SFS, 6, 6), 'Strategies for Success'))

// Horizontal lockup
function horizontal(ink, accent, file) {
  const s = 0.72
  const mh = MARK_H * s
  const tx = MARK_W * s + 26
  const l1 = text('Strategies for Excellence', sansBold, 34, tx, 40, -0.02)
  const l2 = text('RCM SOLUTIONS', sansSemi, 12.5, tx + 1, 62, 0.34)
  const w = tx + Math.max(l1.width, l2.width) + 4
  const body =
    defs('h', 0, MARK_W) +
    markGroup('h', SFE, 0, (76 - mh) / 2, s) +
    `<path fill="${ink}" d="${l1.d}"/><path fill="${accent}" d="${l2.d}"/>`
  out(file, svg(w, 76, body, 'Strategies for Excellence'))
}
horizontal('#1B1A3A', '#0F7C7A', 'sfe-logo-horizontal.svg')
horizontal('#FFFFFF', '#8DD3C7', 'sfe-logo-horizontal-white.svg')

// Stacked lockup (mirrors the original: mark over wordmark between hairlines)
function stacked(lettersD, word, ink, file, title) {
  const W = 420
  const mx = (W - MARK_W) / 2
  const t = text(word, sansSemi, 26, 0, 0, 0.01)
  const tx = (W - t.width) / 2
  const line = text(word, sansSemi, 26, tx, 148, 0.01)
  const rule = `<g stroke="${ink}" stroke-opacity=".35" stroke-width="1"><path d="M8 139H${r2(tx - 14)}"/><path d="M${r2(tx + t.width + 14)} 139H${W - 8}"/></g>`
  const body = defs('st', 0, MARK_W) + markGroup('st', lettersD, mx, 8) + `<path fill="${ink}" d="${line.d}"/>` + rule
  out(file, svg(W, 166, body, title))
}
stacked(SFE, 'Strategies for Excellence', '#2A294D', 'sfe-logo-stacked.svg', 'Strategies for Excellence')
stacked(SFS, 'Strategies for Success', '#2A294D', 'sfs-logo-original-stacked.svg', 'Strategies for Success')

// Favicon: rounded square with signature gradient + monogram
{
  const fav = [glyph('S', 17.5, 33, 27), glyph('f', 32, 33, 30), glyph('E', 46.5, 33, 25)]
  const body = `<defs><linearGradient id="f-g" x1="0" y1="0" x2="64" y2="64" gradientUnits="userSpaceOnUse">${STOPS}</linearGradient></defs>
<rect width="64" height="64" rx="16" fill="url(#f-g)"/><g fill="#fff">${fav.map((d) => `<path d="${d}"/>`).join('')}</g>`
  writeFileSync(resolve(root, 'public/favicon.svg'), svg(64, 64, body, 'SfE'))
}

console.log('Logo assets generated.')
